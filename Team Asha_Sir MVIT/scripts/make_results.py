#!/usr/bin/env python3
"""Generate RESULTS.md from the canonical dashboard data payload."""

from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DATA_PATH = ROOT / "dashboard" / "twin_data.json"
OUTPUT_PATH = ROOT / "RESULTS.md"


def fmt(value: float, digits: int = 4) -> str:
    return f"{value:.{digits}f}"


def fmt_p(value: float) -> str:
    """Format p-values without implying more precision than the source data.

    Below 1e-5 the fixed 5-decimal form would round to "0", so switch to
    scientific notation there. The cut-off is 1e-5, not 1e-4, so that current
    values such as 9e-05 keep their existing "0.00009" rendering.
    """
    if value < 1e-5:
        return f"{value:.2e}"
    return f"{value:.5f}".rstrip("0").rstrip(".")


def main() -> None:
    data = json.loads(DATA_PATH.read_text())
    meta = data["meta"]
    horizons = data["horizons"]
    curve = data["horizon_curve"]
    prevalence = data["prevalence"]
    burden = data["burden"]

    lines = [
        "# Results — Team Asha",
        "",
        "Generated by `scripts/make_results.py` from `dashboard/twin_data.json`; do not edit this file by hand.",
        "",
        f"Episode-level cohort: {meta['n_patients']} patients, {meta['n_windows']:,} windows; subject-grouped {meta['folds']}-fold CV.",
        f"Final model results are averaged over {len(meta['seeds'])} seeds.",
        "",
        "## Burden estimation",
        "",
        "Primary result: concurrent, out-of-fold estimation of FoG burden on held-out patients; not prospective forecasting of future burden.",
        "",
        f"- Spearman ρ = {burden['spearman_r']:.3f}, p = {fmt_p(burden['spearman_p'])} (n = {burden['n_patients']}).",
        f"- Pearson r = {burden['pearson_r']:.3f}, p = {fmt_p(burden['pearson_p'])}.",
        f"- NFOGQ alone: r = {burden['nfogq_alone_r']:.3f}, p = {fmt_p(burden['nfogq_alone_p'])}.",
        f"- Partial correlation controlling for NFOGQ: r = {burden['partial_r_nfogq']:.3f}, p = {fmt_p(burden['partial_p_nfogq'])}.",
        f"- Partial correlation controlling for activity level: r = {burden['partial_r_activity']:.3f}, p = {fmt_p(burden['partial_p_activity'])}.",
        "",
        "Caveats: single cohort, correlational, and no external validation. "
        "Spearman is the headline statistic because Pearson is leverage-sensitive: "
        f"excluding the single highest-burden patient gives r = {burden['jackknife_r_min']:.3f} (p = {fmt_p(burden['jackknife_p_max'])}); "
        f"across all leave-one-patient-out deletions r spans {burden['jackknife_r_min']:.3f}–{burden['jackknife_r_max']:.3f}, "
        f"all p ≤ {fmt_p(burden['jackknife_p_max'])}.",
        "",
        f"Inference treats the {burden['n_patients']} patients as the independent units (one estimate and one observed rate per patient), "
        f"not the {meta['n_windows']:,} windows; `scripts/burden_analysis.py` recomputes every statistic above from the {burden['n_patients']} per-patient rows.",
        "",
        "## Horizon curve",
        "",
        "AUPRC mean over folds; chance level is prevalence.",
        "",
        "| Horizon (s) | A | B | C | Prevalence floor |",
        "|---:|---:|---:|---:|---:|",
    ]
    for i, horizon in enumerate(horizons):
        lines.append(
            f"| {horizon:.1f} | {fmt(curve['A'][i])} | {fmt(curve['B'][i])} | "
            f"{fmt(curve['C'][i])} | {fmt(prevalence[i])} |"
        )

    lines.extend([
        "",
        "## Submitted model",
        "",
        str(meta["submitted_model"]),
        "",
        "Model C is submitted even though it does not outperform the accelerometry-only arm (A) in the ablation, because it is the only arm that uses both required data streams, static clinical state and dynamic accelerometry, and the challenge requires two-stream fusion.",
        "",
        "## Personalisation",
        "",
        "| Mechanism | Change | Wins |",
        "|---|---:|---:|",
    ])
    for result in data["nulls"]:
        lines.append(f"| {result['mechanism']} | {result['delta']:+.4f} | {result['wins']} |")

    heterogeneity = data["heterogeneity"]
    lines.extend([
        "",
        "## Heterogeneity",
        "",
        f"- {heterogeneity['below_2x']}/{heterogeneity['n_evaluated']} patients have a per-patient AUPRC below twice their own event rate at the {meta['horizon_s']:.1f} s horizon.",
        f"- Per-patient optimal thresholds span {heterogeneity['threshold_min']:.3f}–{heterogeneity['threshold_max']:.4f}; the global threshold is {meta['threshold_global']:.3f}.",
        "",
        "## Operating points",
        "",
        "Alarm-state percentage is the monitored time in an alarm state at each operating point.",
        "",
        "| Recall target | Alarm state (% of monitored time) | Precision |",
        "|---:|---:|---:|",
    ])
    for point in data["operating_points"]:
        lines.append(
            f"| {point['recall']:.0%} | {point['pct_time_alarming']:.1f}% | {point['precision']:.3f} |"
        )
    lines.extend([
        "",
        "Caveat: evaluation is on FoG-provoking protocol segments, not free-living monitoring.",
        "",
    ])
    OUTPUT_PATH.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
